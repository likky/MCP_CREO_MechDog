// panel_selection_state.h — BUG-120/D3: one selection, one ticket, one order.
//
// The dialog-driven route injects references into a live panel. Two failures are
// recorded in the field notes and both are state problems, not geometry problems:
//
// - the same position selected twice toggles itself back out (TOGGLE semantics),
//   and an old macro from the previous job runs against the new dialog;
// - a Done is queued while the panel is still open, so "queued" is mistaken for
//   "finished".
//
// This state machine makes both impossible to express:
//
// - every position gets exactly one one-shot ticket, bound to job, nonce and model;
//   a consumed, stale, out-of-order or foreign ticket does not advance anything;
// - the first position uses OVERRIDE (replace the dialog's selection) and later
//   positions use TOGGLE (add to it), each at most once;
// - only a successful Done queue enters `done_queued`, and the end sequence must
//   arrive as Done-or-Quit/yes, then AfterTerminal, then OuterDrain with strictly
//   increasing event_seq. A reversed or missing link leaves the run unknown.
//
// A failure sticks. A second Prepare is refused while a run is active and after a
// failure; changing the request id is not a reset. No Toolkit call is made here, so
// tests/native/test_panel_selection_state.cpp can prove every rule offline.
#ifndef MECHDOG_PANEL_SELECTION_STATE_H
#define MECHDOG_PANEL_SELECTION_STATE_H

#include <string>
#include <vector>

#include "panel_protocol.h"

namespace mechdog_panel {

enum class PanelSelectionAction {
    None,
    Override,
    Toggle
};

enum class PanelStage {
    Idle,
    Prepared,
    DoneQueued,
    AfterTerminal,
    OuterDrained,
    Locked,
};

inline const char *panel_stage_name(PanelStage stage) {
    switch (stage) {
    case PanelStage::Idle:
        return "idle";
    case PanelStage::Prepared:
        return "prepared";
    case PanelStage::DoneQueued:
        return "done_queued";
    case PanelStage::AfterTerminal:
        return "after_terminal";
    case PanelStage::OuterDrained:
        return "outer_drained";
    case PanelStage::Locked:
        return "locked";
    }
    return "unknown";
}

//: One one-shot ticket. ``ticket_id`` is generated by the state machine at prepare
//: time, so a caller cannot invent one; the rest is the identity it must match.
struct PanelTicket {
    std::string ticket_id;
    int slot = 0;
    //: 0 = first direction (sections), 1 = second direction (guides). It only
    //: decides the selection action; the ticket identity stays request/nonce/slot.
    int direction = 0;
    //: True for the first position of its direction: the collector starts empty (or
    //: the dialog still holds the other direction's picks), so that injection replaces.
    bool override = false;
    std::string job_id;
    std::string nonce;
    std::string model_name;
    std::string model_id;
};

//: A native end-of-run event. ``kind`` is one of the strings below; the collector
//: fills it from the callback, never from the request file.
struct PanelEvent {
    std::string kind; // done | quit_yes | after_terminal | outer_drain
    int event_seq = 0;
    std::string job_id;
    std::string nonce;
};

struct PanelVerdict {
    bool ok = false;
    std::string code;
    std::string message;
    PanelSelectionAction action = PanelSelectionAction::None;
};

namespace detail {

inline PanelVerdict refusal(const std::string &code, const std::string &message) {
    PanelVerdict verdict;
    verdict.code = code;
    verdict.message = message;
    return verdict;
}

inline PanelVerdict acceptance(PanelSelectionAction action) {
    PanelVerdict verdict;
    verdict.ok = true;
    verdict.action = action;
    return verdict;
}

} // namespace detail

class PanelSelectionState {
  public:
    //: Register the run and its positions. ``tickets_registered`` is false when the
    //: native side registered fewer tickets than positions: the run must not start,
    //: because a half-registered dialog cannot be selected into and cannot be
    //: cleaned up by this state machine.
    PanelVerdict prepare(const std::string &request_id, const std::string &job_id,
                         const std::string &nonce, const std::string &model_name,
                         const std::string &model_id, const std::vector<int> &slots,
                         bool tickets_registered,
                         const std::vector<int> &directions = std::vector<int>()) {
        if (stage_ != PanelStage::Idle)
            // Not sticky: refusing a second Prepare must not destroy the run that
            // already owns the dialog.
            return detail::refusal("PANEL_STATE_NOT_IDLE",
                                   std::string("the panel run is ") + panel_stage_name(stage_) +
                                       "; a new Prepare is refused instead of resetting it");
        if (request_id.empty() || job_id.empty() || nonce.empty() || model_name.empty() ||
            model_id.empty())
            return detail::refusal(
                "PANEL_PREPARE_IDENTITY",
                "Prepare needs the request id, job, nonce, model name and model id");
        if (slots.size() < 2 || slots.size() > (size_t)position_limit)
            return refuse("PANEL_SLOT_COUNT_OUT_OF_RANGE",
                          "the panel route takes 2-" + std::to_string(position_limit) +
                              " positions, received " + std::to_string(slots.size()));
        if ((int)slots.size() > ticket_capacity)
            return refuse("PANEL_TICKET_CAPACITY_EXCEEDED",
                          "more positions than the protocol ticket capacity");
        for (size_t index = 0; index < slots.size(); ++index) {
            if (slots[index] < 0)
                return refuse("PANEL_SLOT_INVALID", "a position cannot be negative");
            for (size_t other = index + 1; other < slots.size(); ++other)
                if (slots[index] == slots[other])
                    return refuse("PANEL_SLOT_DUPLICATE", "position " +
                                                              std::to_string(slots[index]) +
                                                              " was prepared twice");
        }
        if (!directions.empty()) {
            // BUG-120/D7: the run has one collector switch, so the groups must be 0
            // then 1, in order; a direction that restarts would ask for a second
            // switch the recorded macro does not contain.
            if (directions.size() != slots.size())
                return refuse("PANEL_DIRECTION_COUNT",
                              "the direction groups and the positions disagree");
            for (size_t index = 0; index < directions.size(); ++index) {
                if (directions[index] != 0 && directions[index] != 1)
                    return refuse("PANEL_DIRECTION_INVALID",
                                  "a panel position belongs to direction 0 or 1, received " +
                                      std::to_string(directions[index]));
                if (index > 0 && directions[index] < directions[index - 1])
                    return refuse("PANEL_DIRECTION_ORDER",
                                  "a direction cannot restart after the collector switched away");
            }
        }
        if (!tickets_registered)
            return refuse("PANEL_TICKET_REGISTRATION_FAILED",
                          "the native side registered fewer tickets than positions; the UI was "
                          "not started and nothing was selected");
        request_id_ = request_id;
        job_id_ = job_id;
        nonce_ = nonce;
        model_name_ = model_name;
        model_id_ = model_id;
        slots_ = slots;
        tickets_.clear();
        tickets_.reserve(slots.size());
        for (size_t index = 0; index < slots.size(); ++index) {
            PanelTicket ticket;
            ticket.ticket_id = ticket_identity(request_id, nonce, slots[index]);
            ticket.slot = slots[index];
            ticket.direction = directions.empty() ? 0 : directions[index];
            ticket.override =
                index == 0 || ticket.direction != (directions.empty() ? 0 : directions[index - 1]);
            ticket.job_id = job_id;
            ticket.nonce = nonce;
            ticket.model_name = model_name;
            ticket.model_id = model_id;
            tickets_.push_back(ticket);
        }
        consumed_.assign(tickets_.size(), false);
        stage_ = PanelStage::Prepared;
        return detail::acceptance(PanelSelectionAction::None);
    }

    //: Consume one ticket and return the injection this position needs.
    PanelVerdict record(const PanelTicket &ticket) {
        if (stage_ != PanelStage::Prepared)
            return refuse("PANEL_STATE_NOT_PREPARED",
                          std::string("no selection is expected while the run is ") +
                              panel_stage_name(stage_));
        // A refused ticket changed nothing on the dialog, so it is refused without
        // locking the run: "does not advance" is the contract, not "aborts".
        if (ticket.job_id != job_id_)
            return detail::refusal("PANEL_TICKET_JOB", "the ticket belongs to another job");
        if (ticket.nonce != nonce_)
            return detail::refusal(
                "PANEL_TICKET_NONCE",
                "the ticket carries a stale nonce; it is an old macro, not this run");
        if (ticket.model_name != model_name_ || ticket.model_id != model_id_)
            return detail::refusal(
                "PANEL_TICKET_MODEL",
                "the ticket was minted for another model; the ids mean nothing here");
        const int index = slot_index(ticket.slot);
        if (index < 0)
            return detail::refusal("PANEL_SLOT_UNKNOWN", "position " + std::to_string(ticket.slot) +
                                                             " was never prepared");
        if (ticket.ticket_id != tickets_[(size_t)index].ticket_id)
            return detail::refusal("PANEL_TICKET_STALE",
                                   "the ticket id does not match this position; a stale macro is "
                                   "not replayed");
        if (consumed_[(size_t)index])
            return detail::refusal(
                "PANEL_TICKET_CONSUMED",
                "position " + std::to_string(ticket.slot) +
                    " was already selected; a second injection would toggle it back");
        if (index != (int)next_index_)
            return detail::refusal(
                "PANEL_SLOT_OUT_OF_ORDER",
                "position " + std::to_string(ticket.slot) +
                    " arrived before the previous one; the dialog selection cannot be "
                    "reconstructed");
        consumed_[(size_t)index] = true;
        ++next_index_;
        // The first position of each direction replaces whatever that collector held;
        // later positions add. A single-direction run therefore keeps the old rule.
        return detail::acceptance(tickets_[(size_t)index].override ? PanelSelectionAction::Override
                                                                   : PanelSelectionAction::Toggle);
    }

    //: Queue the restricted Done after every position was selected. ``queue_code`` is
    //: the Toolkit result of queueing it: a non-zero code never becomes committed.
    PanelVerdict finalize(int queue_code) {
        if (stage_ != PanelStage::Prepared)
            return refuse("PANEL_STATE_NOT_PREPARED",
                          std::string("Done cannot be queued while the run is ") +
                              panel_stage_name(stage_));
        if (next_index_ != tickets_.size()) {
            const PanelVerdict verdict =
                refuse("PANEL_SELECTION_INCOMPLETE",
                       "not every position was selected; a partial selection is not a surface");
            lock(verdict.code);
            return verdict;
        }
        if (queue_code != 0) {
            const PanelVerdict verdict =
                refuse("PANEL_DONE_QUEUE_FAILED",
                       "queueing the restricted Done returned " + std::to_string(queue_code) +
                           "; this is not a committed result and the panel stays unknown");
            lock(verdict.code);
            return verdict;
        }
        stage_ = PanelStage::DoneQueued;
        return detail::acceptance(PanelSelectionAction::None);
    }

    //: Record the native end-of-run sequence. The order is the contract:
    //: Done (or Quit + yes) -> AfterTerminal -> OuterDrain, with a strictly
    //: increasing event_seq. A tail command arriving on its own proves nothing.
    PanelVerdict observe(const PanelEvent &event) {
        if (event.job_id != job_id_ || event.nonce != nonce_)
            return refuse("PANEL_EVENT_IDENTITY",
                          "the end event does not belong to this job and nonce");
        if (event.event_seq <= last_seq_)
            return refuse("PANEL_EVENT_OUT_OF_ORDER",
                          "event_seq " + std::to_string(event.event_seq) +
                              " does not advance past " + std::to_string(last_seq_));
        if (event.kind == "done" || event.kind == "quit_yes") {
            if (stage_ != PanelStage::DoneQueued && stage_ != PanelStage::Prepared)
                return refuse("PANEL_EVENT_OUT_OF_ORDER",
                              "a terminal event arrived while the run is " +
                                  std::string(panel_stage_name(stage_)));
            if (terminal_seen_)
                return refuse("PANEL_EVENT_OUT_OF_ORDER",
                              "a second terminal event cannot restart the sequence; the first "
                              "one already decided the run's ending");
            terminal_seen_ = true;
            last_seq_ = event.event_seq;
            return detail::acceptance(PanelSelectionAction::None);
        }
        if (event.kind == "after_terminal") {
            if (!terminal_seen_)
                return refuse("PANEL_EVENT_OUT_OF_ORDER",
                              "AfterTerminal arrived before Done or Quit/yes; the tail proves "
                              "nothing on its own");
            terminal_seen_ = false;
            last_seq_ = event.event_seq;
            stage_ = PanelStage::AfterTerminal;
            return detail::acceptance(PanelSelectionAction::None);
        }
        if (event.kind == "outer_drain") {
            if (stage_ != PanelStage::AfterTerminal)
                return refuse("PANEL_EVENT_OUT_OF_ORDER",
                              "OuterDrain arrived before AfterTerminal; the outer macro chain "
                              "was not proven drained after the terminal event");
            last_seq_ = event.event_seq;
            stage_ = PanelStage::OuterDrained;
            return detail::acceptance(PanelSelectionAction::None);
        }
        return refuse("PANEL_EVENT_UNKNOWN", "unknown end event " + event.kind);
    }

    //: True only when the full sequence was observed in order.
    bool closed() const {
        return stage_ == PanelStage::OuterDrained;
    }

    //: Release the run after it ended. A locked run is never released: the failure
    //: is the record, and a new request id is not an exit.
    PanelVerdict release() {
        if (stage_ == PanelStage::Locked)
            return detail::refusal("PANEL_STATE_LOCKED",
                                   "this run failed (" + failure_code_ +
                                       "); it cannot be released and retried in place");
        if (stage_ == PanelStage::Prepared || stage_ == PanelStage::DoneQueued)
            // Not sticky: refusing an early release leaves the run exactly where it
            // was, so the real end sequence can still arrive.
            return detail::refusal("PANEL_STATE_NOT_ENDED",
                                   std::string("the run is still ") + panel_stage_name(stage_) +
                                       "; releasing it would forget an open panel");
        reset();
        return detail::acceptance(PanelSelectionAction::None);
    }

    //: BUG-120/D6: Creo reported the panel command's after-execution bracket. That is
    //: a native close observation, so a run still sitting at Prepared may be reset for
    //: the next request even though this build has no UI event source for the
    //: Done->AfterTerminal->OuterDrain sequence. A locked run is never released.
    PanelVerdict release_observed_close(const std::string &nonce) {
        if (stage_ == PanelStage::Idle)
            return detail::refusal("PANEL_STATE_NOT_PREPARED", "there is no run to release");
        if (stage_ == PanelStage::Locked)
            return detail::refusal("PANEL_STATE_LOCKED",
                                   "this run failed (" + failure_code_ +
                                       "); an observed close does not erase the failure");
        if (nonce != nonce_)
            return detail::refusal("PANEL_NONCE_MISMATCH",
                                   "the close observation belongs to another run");
        reset();
        return detail::acceptance(PanelSelectionAction::None);
    }

    //: Every prepared position was consumed. The native collector asks before it
    //: injects anything, so an extra callback cannot re-toggle the last position.
    bool exhausted() const {
        return next_index_ >= tickets_.size();
    }

    //: Record a native failure that happened *after* a ticket was spent (an SDK
    //: error, an exception at the callback boundary). The run cannot continue as if
    //: nothing happened, and a retry cannot reuse the spent ticket.
    PanelVerdict abandon(const std::string &code) {
        if (stage_ == PanelStage::Idle)
            return detail::refusal("PANEL_STATE_NOT_PREPARED", "there is no run to abandon");
        lock(code);
        return detail::refusal(code, "the run was abandoned after a native failure");
    }

    PanelStage stage() const {
        return stage_;
    }
    const std::string &failure_code() const {
        return failure_code_;
    }
    std::vector<PanelTicket> tickets() const {
        return tickets_;
    }
    int selected() const {
        return (int)next_index_;
    }
    int last_event_seq() const {
        return last_seq_;
    }

  private:
    //: A failure inside a run is the run's record: it locks. A malformed call made
    //: before a run exists is the caller's error and changes nothing.
    PanelVerdict refuse(const std::string &code, const std::string &message) {
        if (stage_ != PanelStage::Idle)
            lock(code);
        return detail::refusal(code, message);
    }

    void lock(const std::string &code) {
        if (stage_ != PanelStage::Locked) {
            stage_ = PanelStage::Locked;
            failure_code_ = code;
        }
    }

    void reset() {
        stage_ = PanelStage::Idle;
        request_id_.clear();
        job_id_.clear();
        nonce_.clear();
        model_name_.clear();
        model_id_.clear();
        slots_.clear();
        tickets_.clear();
        consumed_.assign(tickets_.size(), false);
        next_index_ = 0;
        last_seq_ = 0;
        terminal_seen_ = false;
        failure_code_.clear();
    }

    int slot_index(int slot) const {
        for (size_t index = 0; index < slots_.size(); ++index)
            if (slots_[index] == slot)
                return (int)index;
        return -1;
    }

    static std::string ticket_identity(const std::string &request_id, const std::string &nonce,
                                       int slot) {
        // Deterministic and bound to the run: a ticket from an earlier request (or
        // an earlier nonce) can never collide with this run's ticket.
        return request_id + "/" + nonce + "/" + std::to_string(slot);
    }

    PanelStage stage_ = PanelStage::Idle;
    std::string request_id_;
    std::string job_id_;
    std::string nonce_;
    std::string model_name_;
    std::string model_id_;
    std::vector<int> slots_;
    std::vector<PanelTicket> tickets_;
    std::vector<bool> consumed_;
    size_t next_index_ = 0;
    int last_seq_ = 0;
    bool terminal_seen_ = false;
    std::string failure_code_;
};

} // namespace mechdog_panel

#endif // MECHDOG_PANEL_SELECTION_STATE_H
