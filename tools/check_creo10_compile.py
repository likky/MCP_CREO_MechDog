"""Compile the native code against a Creo 10 SDK without running Creo.

The project builds against the locally installed SDK (Creo 12.4 on this machine).
The target machine runs Creo 10, so every Pro* declaration this code relies on is
currently unproven for that SDK. This script answers exactly that question and
nothing more:

- it compiles the ABI2 payload (``blend_sync.cpp``), the loader and an API probe
  against a copied Creo 10 ``protoolkit/includes`` tree;
- it compiles ``worker.cpp`` only with ``--full`` (slow, but it is the production
  translation unit);
- it regenerates ``constants.inc`` for that SDK inside a sandbox and never touches
  ``native/constants.inc``, so the local Creo 12.4 build is not disturbed.

A pass means "the Creo 10 headers declare these functions with these signatures".
It does NOT mean the panel works, that a dialog opens, or that a curve enumerates
on the target machine: that is D6, and it needs Creo running there.

Usage (sdk root may be the protoolkit dir, the Creo root, or a parent holding either):

    .venv\\Scripts\\python.exe tools\\check_creo10_compile.py --sdk build\\creo10_sdk
    .venv\\Scripts\\python.exe tools\\check_creo10_compile.py --sdk build\\creo10_sdk --full

Report: ``build/creo10_check/report.json`` (plus per-file ``*.log``).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

from creo_mechdog.build_support import compiler_setup_script, validate_local_path
from creo_mechdog.paths import SOURCE_PATHS

#: Functions the new native code calls. A missing one is a compile error, but naming
#: them here also produces a readable pre-check before the compiler runs.
REQUIRED_FUNCTIONS = (
    "ProArraySizeGet",
    "ProArrayAlloc",
    "ProArgumentProarrayFree",
    "ProValuedataWstringSet",
    "ProMdlCurrentGet",
    "ProMdlMdlnameGet",
    "ProModelitemInit",
    "ProSelectionAlloc",
    "ProSelectExternalselectionRecord",
    "ProSelectionFree",
    "ProCmdActionAdd",
    "ProToolkitDllIdGet",
    "ProMacroLoad",
    "ProCmdCmdIdFind",
    "ProCmdBracketFuncAdd",
    "ProFeatureGeomitemVisit",
    "ProCurveInit",
    "ProCurveTypeGet",
    "ProCurveLengthEval",
    "ProFeatureInit",
)

#: Enumerators the new code names. Values may differ between generations; presence
#: is what matters, and the compiler checks that.
REQUIRED_ENUMS = (
    "PRO_SELECT_OVERRIDE",
    "PRO_SELECT_TOGGLE",
    "PRO_ENT_CMP_CRV",
    "uiProeAsynch",
    "PRO_VALUE_TYPE_WSTRING",
    "PRO_TK_NO_ERROR",
)

PROBE = """// Generated by tools/check_creo10_compile.py: takes the address of every API the
// new native code depends on. A signature change in this SDK generation fails here.
#include <ProToolkitDll.h>
#include <ProUICmd.h>
#include <ProMenu.h>
#include <ProFeature.h>
#include <ProCurve.h>
#include <ProSelection.h>
#include <ProMdl.h>
#include <ProModelitem.h>
#include <ProArray.h>
#include "callback_api.h"

int main() {
__FUNCTIONS__
    const int enums[] = {__ENUMS__};
    (void)enums;
    MechDogCallbackApi2 table{};
    return table.abi;
}
"""


def resolve_sdk(given: Path) -> Path | None:
    """Accept the protoolkit dir, the Creo root, or a parent holding either."""
    candidates = [
        given,
        given / "protoolkit",
        given / "Common Files/protoolkit",
    ]
    for candidate in candidates:
        if (candidate / "includes/ProToolkit.h").is_file():
            return candidate
    return None


def header_digest(sdk: Path) -> dict:
    headers = sorted((sdk / "includes").glob("*.h"))
    blob = b"".join(path.read_bytes() for path in headers)
    return {
        "include_dir": str(sdk / "includes"),
        "header_count": len(headers),
        "headers_sha256": hashlib.sha256(blob).hexdigest(),
    }


def symbol_presence(sdk: Path) -> dict:
    include = sdk / "includes"
    text = "\n".join(
        path.read_text(encoding="utf-8", errors="replace") for path in include.glob("*.h")
    )
    return {
        "functions": {
            name: bool(re.search(r"\b" + name + r"\s*\(", text)) for name in REQUIRED_FUNCTIONS
        },
        "enums": {name: bool(re.search(r"\b" + name + r"\b", text)) for name in REQUIRED_ENUMS},
    }


def prepare_sandbox(root: Path, source_native: Path, sdk: Path) -> Path:
    """A private copy of native/ so constants.inc can be regenerated safely."""
    sandbox = root / "build/creo10_check"
    target_native = sandbox / "native"
    if target_native.exists():
        shutil.rmtree(target_native)
    shutil.copytree(source_native, target_native)
    # ``tools`` is a directory of scripts, not a package: import it by path.
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import generate_constants

    generate_constants.generate(sandbox, inc_dir=sdk / "includes")
    return target_native


def run_compile(
    root: Path, sandbox: Path, name: str, source: Path, sdk: Path, definitions: list[str]
) -> dict:
    object_file = sandbox / f"{name}.obj"
    log_file = sandbox / f"{name}.log"
    flags = " ".join(f"/D{d}" for d in definitions)
    command = (
        f"cl /nologo /MD /EHsc /std:c++17 /W3 /we4552 {flags} "
        f'/I"{sdk / "includes"}" /I"{sandbox / "native"}" /c "{source}" /Fo"{object_file}"'
    )
    batch = sandbox / f"{name}.cmd"
    batch.write_text(
        "\n".join(
            [
                "@echo off",
                compiler_setup_script(
                    json.loads((root / "config.json").read_text(encoding="utf-8-sig"))
                ),
                command,
                "if errorlevel 1 exit /b %errorlevel%",
                "exit /b 0",
            ]
        )
        + "\n",
        encoding="utf-8",
    )
    started = time.monotonic()
    with log_file.open("wb") as log:
        completed = subprocess.run(
            ["cmd.exe", "/d", "/c", str(batch)],
            cwd=sandbox,
            stdout=log,
            stderr=subprocess.STDOUT,
            timeout=1800,
            creationflags=subprocess.CREATE_NO_WINDOW if os.name == "nt" else 0,
        )
    errors = []
    for line in log_file.read_text(encoding="utf-8", errors="replace").splitlines():
        stripped = line.strip()
        if "error C" in stripped or "error LNK" in stripped:
            errors.append(stripped[:400])
        if len(errors) >= 20:
            break
    return {
        "translation_unit": source.name,
        "exit_code": completed.returncode,
        "seconds": round(time.monotonic() - started, 1),
        "object": str(object_file) if object_file.exists() else None,
        "errors": errors,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description="Compile the native code against a Creo SDK copy")
    parser.add_argument(
        "--sdk",
        default="build/creo10_sdk",
        help="Creo root, protoolkit dir, or a dir holding either",
    )
    parser.add_argument("--full", action="store_true", help="also compile worker.cpp")
    args = parser.parse_args()

    root = SOURCE_PATHS.resource_root
    given = Path(args.sdk)
    if not given.is_absolute():
        given = root / given
    sdk = resolve_sdk(given)
    if sdk is None:
        print(
            json.dumps(
                {
                    "success": False,
                    "error": "SDK headers not found",
                    "looked_for": str(given / "includes/ProToolkit.h"),
                    "expected_layouts": [
                        "<sdk>/includes/ProToolkit.h",
                        "<sdk>/protoolkit/includes/ProToolkit.h",
                        "<sdk>/Common Files/protoolkit/includes/ProToolkit.h",
                    ],
                    "what_to_copy": (
                        "Copy the Creo 10 'Common Files/protoolkit/includes' directory to this machine, "
                        "e.g. build/creo10_sdk/includes (only headers are needed for a compile check)"
                    ),
                },
                indent=2,
            )
        )
        return 2
    for path in (root / "build", root / "native"):
        validate_local_path(str(path), "creo10 compile check path")

    sandbox = root / "build/creo10_check"
    sandbox.mkdir(parents=True, exist_ok=True)
    native = prepare_sandbox(root, root / "native", sdk)

    probe = sandbox / "api_probe.cpp"
    # No str.format here: the probe contains C++ braces of its own.
    probe.write_text(
        PROBE.replace(
            "__FUNCTIONS__",
            "\n".join(
                f"    auto fn_{index} = &{name}; (void)fn_{index};"
                for index, name in enumerate(REQUIRED_FUNCTIONS)
            ),
        ).replace("__ENUMS__", ", ".join(f"(int){name}" for name in REQUIRED_ENUMS)),
        encoding="utf-8",
    )

    units = [
        ("api_probe", probe),
        ("blend_sync", native / "blend_sync.cpp"),
        ("blend_loader", native / "blend_loader.cpp"),
    ]
    if args.full:
        units.append(("worker", native / "worker.cpp"))

    results = []
    for name, source in units:
        definitions = ["PRO_MACHINE=36", "PRO_OS=4"]
        if name == "worker":
            definitions.append("PRO_USE_VAR_ARGS")
        results.append(run_compile(root, sandbox, name, source, sdk, definitions))

    report = {
        "timestamp_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "sdk": header_digest(sdk) | {"resolved_from": str(given)},
        "symbols_in_headers": symbol_presence(sdk),
        "compile": results,
        "full": bool(args.full),
        "verdict": (
            "compiles against this SDK; runtime behaviour on the target machine is NOT proven"
            if all(item["exit_code"] == 0 for item in results)
            else "compile failed against this SDK; see compile[].errors"
        ),
        "success": all(item["exit_code"] == 0 for item in results),
    }
    (sandbox / "report.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    print(json.dumps(report, indent=2))
    return 0 if report["success"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
